static int c_CreateContext(Cpu *c)
{
    void *host = 0;
    Proxy *share = A(1) ? proxy_find(A(1)) : 0, *p;
    int err;
    if (!gl_ready()) RET(kCGLBadCodeModule);
    if (A(1) && !share) RET(kCGLBadContext);
    err = H.CreateContext(AP(0), share ? share->host : 0, &host);
    if (!err && host) {
        GlCx *x = host;
        p = proxy_new(host);
        state_share(host, share ? share->host : 0);
        if (!p) { H.DestroyContext(host); RET(10016); }
        /* the driver swaps 16- and 32-bit pixel components: Intel byte order (glPixelStore turns it around) */
        ((void (*)(void *, uint32_t, uint32_t))x->disp[g_slot_pixel_storei])(x->rend, GL_UNPACK_SWAP_BYTES, 1);
        ((void (*)(void *, uint32_t, uint32_t))x->disp[g_slot_pixel_storei])(x->rend, GL_PACK_SWAP_BYTES, 1);
        out32(A(2), p->g);
    } else out32(A(2), 0);
    RET(err);
}
static void forget_everywhere(Proxy *p, Cpu *c)
{
    if (c->gl_proxy == p->g) set_current(c, 0);
}
static int c_DestroyContext(Cpu *c)
{
    int err;
    CTX(0);
    err = H.DestroyContext(p->host);
    state_free(p->host);
    forget_everywhere(p, c);
    proxy_free(p);
    RET(err);
}
static int c_RetainContext(Cpu *c) { CTX(0); H.RetainContext(p->host); p->refs++; RET(p->g); }
static int c_ReleaseContext(Cpu *c)
{
    CTX(0);
    H.ReleaseContext(p->host);
    if (--p->refs <= 0) { state_free(p->host); forget_everywhere(p, c); proxy_free(p); }
    RET(0);
}
