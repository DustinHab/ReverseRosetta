/* ---------- names ---------- */

#define NHASH 4096
static short g_hash[NHASH];                     /* index into g_glname + 1, CGL: -(index + 1) */
static int g_hash_done;

static uint32_t hname(const char *s, size_t n)
{
    uint32_t h = 2166136261u;
    while (n--) h = (h ^ (unsigned char)*s++) * 16777619u;
    return h & (NHASH - 1);
}

static void hash_build(void)
{
    unsigned i;
    uint32_t h;
    for (i = 0; i < GL_NNAME; i++) {
        h = hname(g_glname[i].name, strlen(g_glname[i].name));
        while (g_hash[h]) h = (h + 1) & (NHASH - 1);
        g_hash[h] = (short)(i + 1);
    }
    for (i = 0; i < NCGL; i++) {
        h = hname(g_cgl[i].name, strlen(g_cgl[i].name));
        while (g_hash[h]) h = (h + 1) & (NHASH - 1);
        g_hash[h] = (short)-(int)(i + 1);
    }
    g_hash_done = 1;
}

Stub gl_stub(const char *s, size_t n)
{
    uint32_t h;
    if (n < 3 || !((s[0] == 'g' && s[1] == 'l') || (s[0] == 'C' && s[1] == 'G' && s[2] == 'L'))) return 0;
    if (!g_hash_done) hash_build();
    for (h = hname(s, n); g_hash[h]; h = (h + 1) & (NHASH - 1)) {
        int k = g_hash[h];
        const char *name = k > 0 ? g_glname[k - 1].name : g_cgl[-k - 1].name;
        if (strlen(name) == n && !memcmp(name, s, n))
            return k > 0 ? g_gl_api[g_glname[k - 1].slot] : g_cgl[-k - 1].fn;
    }
    return 0;
}

const char *gl_name(Stub fn)
{
    unsigned i;
    for (i = 0; i < GL_NSLOT; i++) if (g_gl_api[i] == fn || g_gl_disp[i] == fn) return g_glslot[i].name;
    for (i = 0; i < NCGL; i++) if (g_cgl[i].fn == fn) return g_cgl[i].name;
    return 0;
}
