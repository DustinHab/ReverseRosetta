/* ---------- calls of the host OpenGL into CoreGraphics ----------
 * The host OpenGL talks to the WindowServer only in OpenGL.framework itself (CGS functions through its lazy
 * symbol pointers). rebind() points such a pointer at a function of rosetta. */
#include <mach-o/dyld.h>
#include <mach-o/loader.h>
#include <mach-o/nlist.h>

static int rebind(const char *image, const char *symbol, void *fn, void **old)
{
    uint32_t i, k, n = _dyld_image_count();
    for (i = 0; i < n; i++) {
        const struct mach_header *mh = _dyld_get_image_header(i);
        const char *name = _dyld_get_image_name(i);
        intptr_t slide = _dyld_get_image_vmaddr_slide(i);
        const struct load_command *lc;
        const struct symtab_command *st = 0;
        const struct dysymtab_command *dy = 0;
        const struct segment_command *le = 0;
        const uint8_t *base;
        const uint32_t *ind;
        const struct nlist *sym;
        const char *str;
        if (!name || !strstr(name, image) || mh->magic != MH_MAGIC) continue;
        lc = (const struct load_command *)(mh + 1);
        for (k = 0; k < mh->ncmds; k++, lc = (const struct load_command *)((const uint8_t *)lc + lc->cmdsize)) {
            if (lc->cmd == LC_SYMTAB) st = (const void *)lc;
            else if (lc->cmd == LC_DYSYMTAB) dy = (const void *)lc;
            else if (lc->cmd == LC_SEGMENT && !strcmp(((const struct segment_command *)lc)->segname, "__LINKEDIT")) le = (const void *)lc;
        }
        if (!st || !dy || !le) continue;
        base = (const uint8_t *)(le->vmaddr + slide - le->fileoff);
        ind = (const uint32_t *)(base + dy->indirectsymoff);
        sym = (const struct nlist *)(base + st->symoff);
        str = (const char *)(base + st->stroff);
        lc = (const struct load_command *)(mh + 1);
        for (k = 0; k < mh->ncmds; k++, lc = (const struct load_command *)((const uint8_t *)lc + lc->cmdsize)) {
            const struct segment_command *sg = (const void *)lc;
            const struct section *se = (const struct section *)(sg + 1);
            uint32_t j, q;
            if (lc->cmd != LC_SEGMENT) continue;
            for (j = 0; j < sg->nsects; j++, se++) {
                uint32_t type = se->flags & SECTION_TYPE;
                void **ptr = (void **)(se->addr + slide);
                if (type != S_LAZY_SYMBOL_POINTERS && type != S_NON_LAZY_SYMBOL_POINTERS) continue;
                for (q = 0; q < se->size / 4; q++) {
                    uint32_t s = ind[se->reserved1 + q];
                    if (s & (INDIRECT_SYMBOL_LOCAL | INDIRECT_SYMBOL_ABS)) continue;
                    if (strcmp(str + sym[s].n_un.n_strx, symbol)) continue;
                    if (old) {                  /* the real target: a lazy pointer may still lead to dyld's binder */
                        *old = dlsym(RTLD_DEFAULT, symbol + 1);
                        if (!*old) *old = ptr[q];
                    }
                    ptr[q] = fn;
                    return 1;
                }
            }
        }
    }
    return 0;
}

