/* glGet*v: count by pname; the swap flags reported as the guest set them */
static int gl_swap_pname(uint32_t p) { return p == GL_UNPACK_SWAP_BYTES || p == GL_PACK_SWAP_BYTES; }
static void gl_get(Cpu *c, GlCx *x, uint32_t a, int slot, int esz)
{
    uint32_t pname = GI(0), n = gl_pcount(c, slot, pname), i;
    uint64_t b[64];
    void *p = GP(4);
    if (!p) return;
    ((void (*)(void *, uint32_t, void *))x->disp[slot])(x->rend, pname, b);
    if (gl_swap_pname(pname)) {
        if (esz == 1) ((uint8_t *)b)[0] = !((uint8_t *)b)[0];
        else if (esz == 4 && slot == g_slot_get_integerv) ((uint32_t *)b)[0] = !((uint32_t *)b)[0];
        else if (esz == 4) ((float *)b)[0] = ((float *)b)[0] != 0.0f ? 0.0f : 1.0f;
        else ((double *)b)[0] = ((double *)b)[0] != 0.0 ? 0.0 : 1.0;
    }
    if (esz == 1) for (i = 0; i < n; i++) st8((uint32_t)(uintptr_t)p + i, ((uint8_t *)b)[i]);
    else if (esz == 4) gl_out_i(p, b, n);
    else gl_out_d(p, b, n);
}
