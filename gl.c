/* ---------- guest context objects ---------- */

/* object in guest memory: rend (its own address), the dispatch table (addresses in the trampoline page), priv,
   stak, all in Intel byte order */
typedef struct Proxy {
    uint32_t g;
    GlCx *host;
    int gcid, refs;
    uint8_t *off_host;                          /* CGLSetOffScreen: the host renders here ... */
    uint32_t off_guest, off_size;               /* ... and rosetta copies it to the guest's buffer, swapped */
    struct Proxy *next;
} Proxy;
static Proxy *g_proxies;
static uint32_t g_tramp, g_null;                /* trampoline page; object of "no context" */

static uint32_t guest_object(void)
{
    uint32_t *o = calloc(GL_NSLOT + 3, 4), g, i;
    if (!o) return 0;
    g = (uint32_t)(uintptr_t)o;
    st32(g, g);
    for (i = 0; i < GL_NSLOT; i++) st32(g + 4 + 4 * i, g_tramp + 4 * i);
    return g;
}

static void tramp_make(void)
{
    size_t sz = ((size_t)GL_NSLOT * 4 + 4095) & ~(size_t)4095;
    void *p = mmap(0, sz, PROT_READ | PROT_WRITE, MAP_ANON | MAP_PRIVATE, -1, 0);
    if (p == MAP_FAILED) return;
    memset(p, 0xc3, sz);                        /* ret, in case anything decoded it */
    mprotect(p, sz, PROT_READ | PROT_EXEC);
    g_tramp = (uint32_t)(uintptr_t)p;
    g_null = guest_object();
}

Stub gl_tramp(uint32_t eip)
{
    uint32_t k = eip - g_tramp;
    if (!g_tramp || k >= 4u * GL_NSLOT || (k & 3)) return 0;
    return g_gl_disp[k / 4];
}

static Proxy *proxy_find(uint32_t g)
{
    Proxy *p;
    for (p = g_proxies; p; p = p->next) if (p->g == g) return p;
    return 0;
}

static GlCx *gl_rend(Cpu *c, uint32_t r)
{
    Proxy *p;
    if (r == c->gl_proxy) return c->gl_ctx;
    p = proxy_find(r);
    return p ? p->host : 0;
}

static Proxy *proxy_new(void *host)
{
    Proxy *p = calloc(1, sizeof *p);
    if (!p) return 0;
    if (!g_tramp) tramp_make();
    p->g = guest_object();
    p->host = host;
    p->refs = 1;
    p->next = g_proxies;
    g_proxies = p;
    return p;
}

static void proxy_free(Proxy *p)
{
    Proxy **q;
    free(p->off_host);
    for (q = &g_proxies; *q; q = &(*q)->next) if (*q == p) { *q = p->next; break; }
    free((void *)(uintptr_t)p->g);
    free(p);
}

static void set_current(Cpu *c, Proxy *p)
{
    c->gl_ctx = p ? p->host : 0;
    c->gl_proxy = p ? p->g : 0;
    if (c->gs_base) st32(c->gs_base + GL_TSD, p ? p->g : g_null);
}

/* offscreen context: the host's pixels to the guest's buffer, every 32-bit pixel swapped */
static void offscreen_sync(GlCx *x)
{
    Proxy *p;
    uint32_t i;
    for (p = g_proxies; p && p->host != x; p = p->next) ;
    if (!p || !p->off_host) return;
    for (i = 0; i + 4 <= p->off_size; i += 4) st32(p->off_guest + i, *(uint32_t *)(p->off_host + i));
}
static void gl_x_finish(Cpu *c, GlCx *x, uint32_t a)
{
    Cpu *fc = glock_release();                  /* waits for the chip */
    ((void (*)(void *))x->disp[g_slot_finish])(x->rend);
    glock_acquire(fc);
    offscreen_sync(x);
    (void)c; (void)a;
}
static void gl_x_flush(Cpu *c, GlCx *x, uint32_t a)
{
    ((void (*)(void *))x->disp[g_slot_flush])(x->rend);
    offscreen_sync(x);
    (void)c; (void)a;
}

