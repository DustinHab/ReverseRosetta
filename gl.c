static int c_ChoosePixelFormat(Cpu *c)
{
    int at[128], n = 0, k = 0, err;
    void *pf = 0;
    uint32_t a = A(0);
    if (!gl_ready()) RET(kCGLBadCodeModule);
    while (a && n < 126) {
        uint32_t v = ld32(a + 4 * k++);
        at[n++] = (int)v;
        if (!v) break;
        switch (v) {                            /* attributes with a value */
        case 7: case 8: case 11: case 12: case 13: case 14: case 55: case 56: case 70: case 84: case 128:
            at[n++] = (int)ld32(a + 4 * k++);
        }
    }
    at[n] = 0;
    err = H.ChoosePixelFormat(at, &pf, &n);
    out32(A(1), (uint32_t)(uintptr_t)pf);
    out32(A(2), (uint32_t)n);
    RET(err);
}
