/* The WindowServer lets only the connection that created a window bind a surface of it (CGSBindSurface; before
   that the host's CoreGraphics asks with message 29272 whether the window is its own), and it knows a connection
   by the port a message arrives on. The host's CoreGraphics therefore sends what it sends on its own connection
   port on the guest's connection port instead: for the WindowServer the host's OpenGL is then the program. */
#include <mach/mach.h>
static mach_msg_return_t (*g_cg_msg)(mach_msg_header_t *, mach_msg_option_t, mach_msg_size_t, mach_msg_size_t,
                                     mach_port_t, mach_msg_timeout_t, mach_port_t);
static mach_port_t g_ws_guest, g_ws_host;     /* connection ports: the guest's main one, the host's */
static uint32_t g_ws_guest_cid;               /* the guest's connection id */
static int g_cg_log;

void gl_ws_connection(uint32_t port, const uint8_t *m, uint32_t n)
{
    if (!g_ws_guest) {
        g_ws_guest = port;
        if (n >= 52) g_ws_guest_cid = *(const uint32_t *)(m + 48);    /* connection id after the port descriptor */
    }
    if (gl_logging()) {
        uint32_t i;
        fprintf(stderr, "[gl] guest WindowServer connection port %x:", port);
        for (i = 24; i + 4 <= n && i < 72; i += 4) fprintf(stderr, " %08x", *(const uint32_t *)(m + i));
        fprintf(stderr, "\n");
    }
}

static mach_msg_return_t cg_msg(mach_msg_header_t *m, mach_msg_option_t o, mach_msg_size_t ss, mach_msg_size_t rs,
                                mach_port_t rp, mach_msg_timeout_t t, mach_port_t n)
{
    mach_msg_return_t r;
    uint32_t i, *w = (uint32_t *)(m + 1);
    if ((o & MACH_SEND_MSG) && g_ws_host && g_ws_guest && m->msgh_remote_port == g_ws_host)
        m->msgh_remote_port = g_ws_guest;
    if (g_cg_log && (o & MACH_SEND_MSG)) {
        fprintf(stderr, "[gl]     host msg id %d to %x size %u:", m->msgh_id, m->msgh_remote_port, ss);
        for (i = 0; i < 8 && 24 + 4 * i < ss; i++) fprintf(stderr, " %08x", w[i]);
        fprintf(stderr, "\n");
    }
    r = g_cg_msg(m, o, ss, rs, rp, t, n);
    if ((o & MACH_RCV_MSG) && !r) {
        if (m->msgh_id == 29901 && !g_ws_host && (m->msgh_bits & MACH_MSGH_BITS_COMPLEX)) g_ws_host = w[1];
        /* owner of a window (reply to 29272): the host's CoreGraphics compares it with its own connection */
        if (m->msgh_id == 29372 && m->msgh_size >= 40 && g_ws_guest_cid && w[3] == g_ws_guest_cid && H.cgs_default)
            w[3] = (uint32_t)H.cgs_default();
        if (g_cg_log) fprintf(stderr, "[gl]     reply id %d: %08x %08x %08x %08x %08x\n", m->msgh_id, w[0], w[1], w[2], w[3], w[4]);
    }
    return r;
}

static void cgs_trace(void)
{
    g_cg_log = 1;
    static const char *const names[] = { "_CGSBindSurface", "_CGSFlushSurfaceWithOptions", "_CGSGetSurfaceBounds",
        "_CGSGetSurfaceOpacity", "_CGSGetWindowBounds", "_CGSOrderSurface", "_CGSSetSurfaceOpacity",
        "_CGSSetWindowSendExposed", "_CGSMainConnectionID", "_CGSGetDenyWindowServerConnections", 0 };
    int k;
    for (k = 0; names[k] && k < CGS_N; k++) {
        g_cgs_name[k] = names[k];
        if (!rebind("/OpenGL.framework/", names[k], g_cgs_w[k], (void **)&g_cgs_orig[k]))
            fprintf(stderr, "[gl] %s: no pointer found\n", names[k]);
    }
}

