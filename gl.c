/* gl.c - OpenGL for translated programs.
 *
 * The Intel OpenGL of the 10.5.8 update cannot draw on a PowerPC Mac: to list its renderers it loads the display's
 * GL driver bundle, which exists only for PowerPC (CGLChoosePixelFormat: 10015, "invalid code module"). rosetta
 * therefore replaces every gl and CGL function of the Intel OpenGL with a call of the PowerPC OpenGL, which draws
 * with the graphics chip. tools/probes/gl_attach.m showed that this works with windows of the translated program:
 * a second WindowServer connection of the process (the host's CoreGraphics) may attach an OpenGL context to a
 * surface that the program's connection added to its window.
 *
 * Calls. Each entry of the dispatch table of a context (GLIFunctionDispatch, 759 entries in 10.5) has a function
 * generated by tools/gl_gen.py (gl_table.h) with the exact prototype: it reads the arguments from the Intel stack,
 * converts arrays of more than one byte per element (vectors, matrices, parameters by pname, lists of names) and
 * calls the entry of the host context directly, without the host libGL in between. Two ways lead there:
 *   - the exported gl functions of the Intel libGL (their entry addresses and the symbol stubs of the callers, see
 *     thunk.c): arguments from esp + 4, the context is the current one of the thread;
 *   - the dispatch table of the guest context: code that uses CGL macros (Apple's GLU does) reads the current
 *     context from its thread-specific slot (%gs:0xc0) and calls ctx->disp.entry(ctx->rend, ...). rosetta gives the
 *     guest its own context object in guest memory: rend is its own address, each dispatch entry an address in a
 *     page that only thunk.c recognises (gl_tramp), so the call reaches the same function, arguments from esp + 8.
 *
 * Pixel data (textures, glReadPixels, glDrawPixels ...) is not copied: every host context has GL_UNPACK_SWAP_BYTES
 * and GL_PACK_SWAP_BYTES set the other way round than the guest set them, so the driver reads and writes the
 * Intel byte order of 16- and 32-bit components and packed pixels itself; glGet reports the guest's setting.
 */
