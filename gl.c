static void gl_unknown(int slot)
{
    if (slot < 1024 && !g_unknown_said[slot]) {
        g_unknown_said[slot] = 1;
        fprintf(stderr, "rosetta: OpenGL %s: an array argument is passed unconverted\n", g_glslot[slot].name);
    }
}

static uint32_t gl_pcount(Cpu *c, int slot, uint32_t p)
{
    (void)slot;
    switch (p) {
    case 0x0BA6: case 0x0BA7: case 0x0BA8: case 0x80B1: case 0x84E3: case 0x84E4: case 0x84E5: case 0x84E6:
        return 16;                              /* matrices */
    case 0x0B00: case 0x0B03: case 0x0B04: case 0x0B06: case 0x0B07: case 0x0B53: case 0x0B66: case 0x0B80:
    case 0x0BA2: case 0x0C10: case 0x0C22: case 0x0C23: case 0x0DD2: case 0x8005: case 0x8459:
    case 0x1200: case 0x1201: case 0x1202: case 0x1203: case 0x1600: case 0x1602: case 0x2201: case 0x2501:
    case 0x2502: case 0x1004: case 0x8154: case 0x8014: case 0x8015: case 0x80D6: case 0x80D7: case 0x8626:
        return 4;                               /* colors, rectangles, positions, planes */
    case 0x0B02: case 0x1204: case 0x1603: case 0x8129:
        return 3;                               /* normal, spot direction, color indexes, point attenuation */
    case 0x0B12: case 0x0B22: case 0x0B40: case 0x0B70: case 0x0D3A: case 0x0DD0: case 0x0DD3: case 0x846D:
    case 0x846E:
        return 2;                               /* ranges, polygon mode, viewport limits */
    case 0x86A3: {                              /* GL_COMPRESSED_TEXTURE_FORMATS: as many as the host has */
        GlCx *x = c->gl_ctx;
        uint32_t n = 0;
        if (x) ((void (*)(void *, uint32_t, uint32_t *))x->disp[g_slot_get_integerv])(x->rend, 0x86A2, &n);
        return n > 64 ? 64 : n;
    }
    }
    return 1;
}

