/* return value float/double on the x87 stack */
static void gl_st0(Cpu *c, double v)
{
    c->st_top = (c->st_top - 1) & 7;
    c->st[c->st_top] = v;
    if (c->x87_depth < 8) c->x87_depth++;
}

